-- AURA customer rewards wheel
-- Separate from the existing authenticated rewards system.

CREATE TABLE IF NOT EXISTS aura_wheel_settings (
  id INTEGER PRIMARY KEY,
  enabled INTEGER NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
  required_orders INTEGER NOT NULL DEFAULT 5 CHECK (required_orders BETWEEN 1 AND 1000),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO aura_wheel_settings (id, enabled, required_orders)
VALUES (1, 0, 5)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS aura_wheel_prizes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('credit', 'product', 'gift')),
  value_iqd INTEGER NOT NULL DEFAULT 0 CHECK (value_iqd >= 0),
  image_url TEXT,
  probability NUMERIC(7,4) NOT NULL CHECK (probability >= 0 AND probability <= 100),
  stock_quantity INTEGER CHECK (stock_quantity IS NULL OR stock_quantity >= 0),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  sequence_position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_aura_wheel_prizes_active
  ON aura_wheel_prizes(active, sequence_position, id);

CREATE TABLE IF NOT EXISTS aura_wheel_spins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  prize_id INTEGER NOT NULL REFERENCES aura_wheel_prizes(id) ON DELETE RESTRICT,
  qualifying_delivered_orders INTEGER NOT NULL CHECK (qualifying_delivered_orders >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_aura_wheel_spins_customer
  ON aura_wheel_spins(customer_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_aura_wheel_spins_prize
  ON aura_wheel_spins(prize_id, created_at, id);

-- Browser roles must never access wheel tables directly.
ALTER TABLE aura_wheel_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE aura_wheel_prizes ENABLE ROW LEVEL SECURITY;
ALTER TABLE aura_wheel_spins ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS aura_wheel_settings_deny_browser ON aura_wheel_settings;
DROP POLICY IF EXISTS aura_wheel_prizes_deny_browser ON aura_wheel_prizes;
DROP POLICY IF EXISTS aura_wheel_spins_deny_browser ON aura_wheel_spins;

CREATE POLICY aura_wheel_settings_deny_browser
  ON aura_wheel_settings
  AS RESTRICTIVE
  FOR ALL
  TO anon, authenticated
  USING (false)
  WITH CHECK (false);

CREATE POLICY aura_wheel_prizes_deny_browser
  ON aura_wheel_prizes
  AS RESTRICTIVE
  FOR ALL
  TO anon, authenticated
  USING (false)
  WITH CHECK (false);

CREATE POLICY aura_wheel_spins_deny_browser
  ON aura_wheel_spins
  AS RESTRICTIVE
  FOR ALL
  TO anon, authenticated
  USING (false)
  WITH CHECK (false);

REVOKE ALL ON aura_wheel_settings FROM PUBLIC, anon, authenticated;
REVOKE ALL ON aura_wheel_prizes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON aura_wheel_spins FROM PUBLIC, anon, authenticated;