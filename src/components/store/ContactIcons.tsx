export function buildWhatsAppUrl(phoneDigits?: string, message?: string): string {
  const digits = (phoneDigits || AURA_CONTACT.whatsappDigits).replace(/[^\d]/g, "");
  const base = `https://wa.me/${digits || AURA_CONTACT.whatsappDigits}`;
  if (message && message.trim()) {
    return `${base}?text=${encodeURIComponent(message.trim())}`;
  }
  return base;
}

export function buildTelHref(phone?: string): string {
  const cleaned = (phone || AURA_CONTACT.phoneDisplay).replace(/[^\d+]/g, "");
  return `tel:${cleaned || AURA_CONTACT.phoneHref}`;
}

